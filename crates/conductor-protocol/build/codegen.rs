//! Generates `src/generated.rs` from `packages/shared/protocol-json` (MR-T03, ADR-0026 §2):
//!
//! ```text
//! pnpm --filter @conductor/shared emit:protocol
//! cargo run -p conductor-protocol-codegen
//! ```
//!
//! 1. Merges every `schemas/*.json` (and their `definitions`) into one set of named definitions.
//! 2. Normalises them for typify (see README §Hand-written parts): `format: date-time` is dropped
//!    (the value stays the exact string the other side sent), and `JsonValue` is inlined as `{}`.
//! 3. Runs typify, then patches every optional + nullable property to a double `Option` so an
//!    explicit `null` and an absent field both survive a round trip.
//! 4. Appends the constants (`constants.json`) and the tool-policy table (`tool-policy.json`).
//! 5. Formats with the pinned `rustfmt`.
//!
//! scripts/ci.sh runs this and fails if the checked-in file changes (the drift check).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::{Map, Value};
use syn::visit_mut::VisitMut;

fn main() {
    // This package is crates/conductor-protocol/build.
    let crate_dir = &Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let json_dir = crate_dir.join("../../packages/shared/protocol-json");
    let out = crate_dir.join("src/generated.rs");

    let defs = load_definitions(&json_dir.join("schemas"));
    let double_options = optional_nullable_fields(&defs);

    let schemas: BTreeMap<String, schemars08::schema::Schema> =
        serde_json::from_value(Value::Object(defs)).expect("schemas parse as JSON Schema");
    let mut settings = typify::TypeSpaceSettings::default();
    settings
        .with_struct_builder(false)
        .with_derive("PartialEq".to_string())
        // Deterministic key order on the wire and in tests (zod doesn't care).
        .with_map_type("::std::collections::BTreeMap");
    let mut space = typify::TypeSpace::new(&settings);
    space
        .add_ref_types(schemas)
        .expect("typify accepts the schemas");

    let mut file: syn::File = syn::parse2(space.to_stream()).expect("typify emits valid Rust");
    let mut patch = DoubleOption {
        wanted: double_options,
        done: BTreeSet::new(),
    };
    patch.visit_file_mut(&mut file);
    let missing: Vec<_> = patch.wanted.difference(&patch.done).collect();
    assert!(
        missing.is_empty(),
        "optional + nullable fields not found in typify output: {missing:?}"
    );

    let mut code = String::from(
        "// @generated by crates/conductor-protocol/build/codegen.rs from\n\
         // packages/shared/protocol-json. Do not edit: change the zod schemas, then run\n\
         // `pnpm --filter @conductor/shared emit:protocol && cargo run -p conductor-protocol-codegen`.\n\n",
    );
    code.push_str(&prettyplease::unparse(&file));
    code.push_str(&constants(&read_json(&json_dir.join("constants.json"))));
    code.push_str(&tool_policy(&read_json(&json_dir.join("tool-policy.json"))));
    std::fs::write(&out, code).expect("write src/generated.rs");
    rustfmt(&out);
    println!("codegen: wrote {}", out.display());
}

fn read_json(path: &Path) -> Value {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

/// Every root schema (named by its file) and every definition, normalised for typify.
fn load_definitions(dir: &Path) -> Map<String, Value> {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .expect("schemas/ exists: run emit:protocol")
        .map(|e| e.expect("readable dir entry").path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    let mut defs = Map::new();
    let mut add = |name: String, schema: Value| {
        if let Some(prev) = defs.get(&name) {
            assert_eq!(
                prev, &schema,
                "definition {name} differs between schema files"
            );
        }
        defs.insert(name, schema);
    };
    for path in files {
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("utf-8 name")
            .to_string();
        let Value::Object(mut root) = read_json(&path) else {
            panic!("{}: not an object", path.display())
        };
        root.remove("$schema");
        if let Some(Value::Object(d)) = root.remove("definitions") {
            for (k, v) in d {
                add(k, v);
            }
        }
        // A registered root is emitted as a bare `$ref` to its own definition.
        if root.get("$ref").and_then(Value::as_str) == Some(&format!("#/definitions/{name}")) {
            continue;
        }
        add(name, Value::Object(root));
    }
    defs.remove("JsonValue");
    let mut defs = Value::Object(defs);
    normalise(&mut defs);
    let Value::Object(defs) = defs else {
        unreachable!()
    };
    defs
}

fn normalise(v: &mut Value) {
    match v {
        Value::Object(o) => {
            // typify maps date-time to chrono, which would re-serialise `…00.000Z` as `…00Z`.
            if o.get("format").and_then(Value::as_str) == Some("date-time") {
                o.remove("format");
            }
            // Any JSON value (zod's `z.json()`) is serde_json::Value.
            if o.get("$ref").and_then(Value::as_str) == Some("#/definitions/JsonValue") {
                o.clear();
            }
            o.values_mut().for_each(normalise);
        }
        Value::Array(a) => a.iter_mut().for_each(normalise),
        _ => {}
    }
}

fn is_nullable(schema: &Value) -> bool {
    let Some(o) = schema.as_object() else {
        return false;
    };
    let null = |t: &Value| t.as_str() == Some("null");
    match o.get("type") {
        Some(Value::Array(ts)) if ts.iter().any(null) => return true,
        Some(t) if null(t) => return true,
        _ => {}
    }
    ["anyOf", "oneOf"].iter().any(|k| {
        o.get(*k)
            .and_then(Value::as_array)
            .is_some_and(|alts| alts.iter().any(is_nullable))
    })
}

/// `(definition, property)` of every property that is both optional and nullable (zod
/// `.nullable().optional()`). It must sit directly in a named definition, so the Rust struct name
/// is known; an inline one fails here (register its object in emit-protocol.ts).
fn optional_nullable_fields(defs: &Map<String, Value>) -> BTreeSet<(String, String)> {
    fn walk(v: &Value, owner: Option<&str>, out: &mut BTreeSet<(String, String)>) {
        match v {
            Value::Object(o) => {
                if let Some(Value::Object(props)) = o.get("properties") {
                    let required: BTreeSet<&str> = o
                        .get("required")
                        .and_then(Value::as_array)
                        .map(|r| r.iter().filter_map(Value::as_str).collect())
                        .unwrap_or_default();
                    for (p, s) in props {
                        if !required.contains(p.as_str()) && is_nullable(s) {
                            let owner = owner.unwrap_or_else(|| {
                                panic!("optional + nullable `{p}` in an unnamed object")
                            });
                            out.insert((owner.to_string(), p.clone()));
                        }
                    }
                    for s in props.values() {
                        walk(s, None, out);
                    }
                }
                for (k, s) in o {
                    if k != "properties" {
                        walk(s, None, out);
                    }
                }
            }
            Value::Array(a) => a.iter().for_each(|s| walk(s, None, out)),
            _ => {}
        }
    }
    let mut out = BTreeSet::new();
    for (name, schema) in defs {
        walk(schema, Some(name), &mut out);
    }
    out
}

/// `Option<T>` + `skip_serializing_if` → `Option<Option<T>>` via `crate::wire::double_option`.
struct DoubleOption {
    wanted: BTreeSet<(String, String)>,
    done: BTreeSet<(String, String)>,
}

impl VisitMut for DoubleOption {
    fn visit_item_struct_mut(&mut self, s: &mut syn::ItemStruct) {
        let owner = s.ident.to_string();
        for field in s.fields.iter_mut() {
            let Some(ident) = &field.ident else { continue };
            let rename = serde_rename(field);
            let key = (
                owner.clone(),
                rename.clone().unwrap_or_else(|| ident.to_string()),
            );
            if !self.wanted.contains(&key) {
                continue;
            }
            let ty = &field.ty;
            field.ty = syn::parse_quote!(::std::option::Option<#ty>);
            field.attrs.retain(|a| !a.path().is_ident("serde"));
            if let Some(rename) = rename {
                field
                    .attrs
                    .push(syn::parse_quote!(#[serde(rename = #rename)]));
            }
            field.attrs.push(syn::parse_quote!(
                #[serde(
                    default,
                    skip_serializing_if = "::std::option::Option::is_none",
                    with = "crate::wire::double_option"
                )]
            ));
            self.done.insert(key);
        }
    }
}

fn serde_rename(field: &syn::Field) -> Option<String> {
    for a in &field.attrs {
        if !a.path().is_ident("serde") {
            continue;
        }
        let mut found = None;
        let _ = a.parse_nested_meta(|m| {
            if m.path.is_ident("rename") {
                let s: syn::LitStr = m.value()?.parse()?;
                found = Some(s.value());
            } else if m.input.peek(syn::Token![=]) {
                let _: syn::Expr = m.value()?.parse()?;
            }
            Ok(())
        });
        if found.is_some() {
            return found;
        }
    }
    None
}

// ---------------------------------------------------------------- constants

fn rust_str(s: &str) -> String {
    format!("{s:?}")
}

fn int_type(name: &str) -> &'static str {
    match name {
        "PROTOCOL_VERSION" => "u32",
        "DEFAULT_CONDUCTOR_PORT" => "u16",
        n if n.starts_with("CLOSE_") => "u16",
        n if n.ends_with("_MS") => "u64",
        _ => "usize",
    }
}

fn constants(c: &Value) -> String {
    let mut out =
        String::from("\n// ---------------------------------------------------- constants.json\n");
    let obj = c.as_object().expect("constants.json is an object");
    for (name, v) in obj {
        match (name.as_str(), v) {
            ("CLOSE_REASONS", Value::Object(m)) => {
                out.push_str(
                    "/// The close reason text sent with each close code (`CLOSE_REASONS`).\n",
                );
                out.push_str("pub fn close_reason(code: u16) -> ::std::option::Option<&'static str> {\n    match code {\n");
                for (code, text) in m {
                    let text = text.as_str().expect("reason text");
                    let _ = writeln!(out, "        {code} => Some({}),", rust_str(text));
                }
                out.push_str("        _ => None,\n    }\n}\n");
            }
            ("API_PATHS", Value::Object(m)) => {
                out.push_str("/// The `API_PATHS` the daemon uses.\npub mod api_paths {\n");
                for (key, path) in m {
                    let path = path.as_str().expect("path string");
                    let snake = snake(key);
                    if let Some((prefix, _param)) = path.split_once("/:") {
                        let _ = writeln!(
                            out,
                            "    pub fn {snake}(param: &str) -> ::std::string::String {{\n        format!(\"{{}}/{{param}}\", {})\n    }}",
                            rust_str(prefix)
                        );
                    } else {
                        let _ = writeln!(
                            out,
                            "    pub const {}: &str = {};",
                            snake.to_uppercase(),
                            rust_str(path)
                        );
                    }
                }
                out.push_str("}\n");
            }
            (_, Value::Number(n)) => {
                let _ = writeln!(out, "pub const {name}: {} = {n};", int_type(name));
            }
            (_, Value::String(s)) => {
                let _ = writeln!(out, "pub const {name}: &str = {};", rust_str(s));
            }
            (_, Value::Array(a)) => {
                let items: Vec<String> = a
                    .iter()
                    .map(|s| rust_str(s.as_str().expect("string item")))
                    .collect();
                let _ = writeln!(out, "pub const {name}: &[&str] = &[{}];", items.join(", "));
            }
            _ => panic!("constants.json: no Rust mapping for {name}"),
        }
    }
    out
}

fn snake(camel: &str) -> String {
    let mut s = String::new();
    for c in camel.chars() {
        if c.is_ascii_uppercase() {
            s.push('_');
            s.push(c.to_ascii_lowercase());
        } else {
            s.push(c);
        }
    }
    s
}

fn tool_policy(p: &Value) -> String {
    let frag = |v: &Value| {
        let list = |k: &str| {
            let items: Vec<String> = v[k]
                .as_array()
                .unwrap_or_else(|| panic!("tool-policy.json: {k}"))
                .iter()
                .map(|s| rust_str(s.as_str().expect("rule string")))
                .collect();
            format!("&[{}]", items.join(", "))
        };
        format!(
            "ToolPolicyFragment {{ builtin: {}, allow: {}, deny: {} }}",
            list("builtin"),
            list("allow"),
            list("deny")
        )
    };
    let mut out = String::from(
        "\n// ---------------------------------------------------- tool-policy.json\n",
    );
    out.push_str(
        "/// One `tools` alias's ToolPolicy fragment (`workflow/tools.ts`).\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub struct ToolPolicyFragment {\n    pub builtin: &'static [&'static str],\n    pub allow: &'static [&'static str],\n    pub deny: &'static [&'static str],\n}\n",
    );
    let _ = writeln!(
        out,
        "/// `BASE_TOOL_POLICY`: every agent gets it.\npub const BASE_TOOL_POLICY: ToolPolicyFragment = {};",
        frag(&p["base"])
    );
    out.push_str("/// `TOOL_ALIASES`, by name.\npub const TOOL_ALIASES: &[(&str, ToolPolicyFragment)] = &[\n");
    for (name, f) in p["aliases"].as_object().expect("aliases object") {
        let _ = writeln!(out, "    ({}, {}),", rust_str(name), frag(f));
    }
    out.push_str("];\n");
    out
}

fn rustfmt(path: &Path) {
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(path)
        .status()
        .expect("run rustfmt");
    assert!(status.success(), "rustfmt failed on {}", path.display());
}
